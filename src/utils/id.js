// =========================================================================
// 📁 src/utils/id.js (產生唯一識別碼)
// =========================================================================
// 前端在兩種情況下需要自行產生 id：
//   1. 樂觀更新時的暫存 id（伺服器回應後會被真實 id 取代）
//   2. 後端資料缺少 id 欄位時的補位
// 原本使用 Math.random()／Date.now() 會讓同一毫秒內的兩次呼叫撞號，
// 也讓單元測試無法預期結果；這裡改用「時間戳 + 遞增序號」，同一個
// session 內保證唯一，且格式固定可測試。

let sequence = 0;

export const createId = (prefix = 'id_') => {
  sequence += 1;
  return `${prefix}${Date.now().toString(36)}_${sequence.toString(36)}`;
};
